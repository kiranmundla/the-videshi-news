#!/usr/bin/env python3
"""
reel_factcheck.py — Phase 1 fact-check gate for The Videshi Pulse reels.

Every factual claim in a reel's on-screen text (names, numbers, dates,
titles) must be verified against the source article BEFORE the reel can
be marked ready. This gate is the direct fix for defect D2 in
research/reel-quality-strategy-2026-10-12.md — the public Short whose
eyebrow read "ELECTIONS 2023" for a 2026-ballot story, because every
string was free-generated by an LLM and nothing ever checked it.

Two layers, both must pass:

  1. DETERMINISTIC grounding (no LLM):
     - Numbers: every number token in the on-screen text (digits, %,
       $, years, ranges) must appear in the article's headline /
       subheadline / body. Normalization handles commas, $ signs,
       crore/lakh/million scaling, spelled-out numbers in the article
       ("nine" -> 9), and fraction phrases ("one-half of 1%" -> 0.5,
       "a quarter" -> 25 in a % context, "a fifth more" -> 20).
     - Names: every capitalized multi-word entity in the on-screen
       text must appear in the article text (case/punctuation
       normalized; sentence-initial capitalization discounted).
       The script's key_entities are checked wholesale.
     - Eyebrow: hook_stat.eyebrow must come from a CLOSED vocabulary
       (free-invented kickers are how D2 happened), or be
       "ELECTIONS <year>" with the year itself grounded.

  2. LLM verification (GPT-4o-mini, temperature 0): per-claim
     supported/unsupported against the article body. Catches what
     string matching cannot: swapped attributions, invented titles,
     plausible-but-absent specifics. Advice/imperative text ("check
     your local rules") is supported unless it asserts a fact the
     article does not contain. Cost is computed from API usage and
     recorded in the report (~$0.001/reel at current prices).
     Verdicts are attributed to claims by the claim text the judge
     echoes back (claim id second) — NEVER positionally: a judge
     that skips or renumbers claims used to shift every later
     verdict onto the wrong claim and leave the tail "missing"
     (2026-10-22 Nasdaq hold, 2026-10-24 SpaceX sample hold).
     Claims left without an attributable verdict are re-asked ONCE;
     still unattributed after that = "judge_error", held and
     labelled as a judge failure, not as an unsupported claim.

A failed claim = the reel is HELD: verdict "fail", the failing claims
named in the report, exit code 1. There is no warn-and-continue.

Usage:
  python3 -u reel_factcheck.py --script script.json \
      (--article article.json | --slug <slug>) [--out report.json] \
      [--no-llm]

Article JSON shape: {headline, subheadline, body, sources, slug}.
Exit codes: 0 pass · 1 held (failed claims) · 4 input/config error.
"""
import argparse, html, json, os, re, subprocess, sys
from pathlib import Path

# ── Claim inventory ─────────────────────────────────────────────────────────
# (field label, text) for every string the renderer puts on screen,
# excluding template-owned strings (brand line, fixed scene eyebrows).
TEMPLATE_OWNED = {
    "what happened", "by the numbers", "why it matters to you",
    "the takeaway", "the videshi", "thevideshi.com",
}

CLOSED_EYEBROWS = {
    "BY THE NUMBERS", "BREAKING", "THE PRICE TAG", "THE BACKLASH",
    "THE STAKES", "WHAT WE KNOW", "THE CONTEXT", "ON THE BALLOT",
    "THE FALLOUT", "THE BIG PICTURE", "THE PRICE OF DIWALI",
}
_EYEBROW_YEAR_RE = re.compile(r"^ELECTIONS (\d{4})$")


def collect_claims(script):
    claims = []

    def add(field, text):
        if text and str(text).strip():
            claims.append({"field": field, "text": str(text).strip()})

    add("hook_line", script.get("hook_line"))
    add("news_summary", script.get("news_summary"))
    hs = script.get("hook_stat") or {}
    add("hook_stat.big", hs.get("big"))
    add("hook_stat.sub", hs.get("sub"))
    add("hook_stat.eyebrow", hs.get("eyebrow"))
    for i, st in enumerate(script.get("stats") or []):
        add(f"stats[{i}].big", st.get("big"))
        add(f"stats[{i}].label", st.get("label"))
    for i, b in enumerate(script.get("diaspora_bullets") or []):
        add(f"diaspora_bullets[{i}]", b)
    add("payoff", script.get("payoff"))
    return claims


# ── Text normalization ──────────────────────────────────────────────────────
def strip_html(s):
    s = re.sub(r"<[^>]+>", " ", s or "")
    return html.unescape(s)


def norm_text(s):
    s = strip_html(s).lower()
    s = s.replace("’", "'").replace("‘", "'").replace("“", '"') \
         .replace("”", '"').replace("–", "-").replace("—", "-")
    s = re.sub(r"[^a-z0-9%$.\- ]+", " ", s)
    return re.sub(r"\s+", " ", s).strip()


# ── Number grounding ────────────────────────────────────────────────────────
_WORD_NUMS = {
    "one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6,
    "seven": 7, "eight": 8, "nine": 9, "ten": 10, "eleven": 11,
    "twelve": 12, "thirteen": 13, "fourteen": 14, "fifteen": 15,
    "sixteen": 16, "seventeen": 17, "eighteen": 18, "nineteen": 19,
    "twenty": 20, "thirty": 30, "forty": 40, "fifty": 50, "sixty": 60,
    "seventy": 70, "eighty": 80, "ninety": 90, "hundred": 100,
}
_SCALE = {"crore": 1e7, "lakh": 1e5, "million": 1e6, "billion": 1e9,
          "thousand": 1e3}
_NUM_RE = re.compile(
    r"\$?\s*(\d[\d,]*(?:\.\d+)?)\s*(%|percent|crore|lakh|million|billion)?")


def _add_num(values, v):
    values.add(round(float(v), 4))


def extract_numbers(text):
    """All normalized numeric values asserted by `text` (raw text).
    Thousands separators are removed BEFORE tokenizing — routing this
    through norm_text would turn "250,000" into "250 000" and silently
    ground wrong amounts ($250,000 vs $250) against each other."""
    t = strip_html(text).lower()
    t = re.sub(r"(?<=\d),(?=\d)", "", t)
    t = t.replace("’", "'").replace("–", "-").replace("—", "-")
    values = set()
    for m in _NUM_RE.finditer(t):
        try:
            v = float(m.group(1).replace(",", ""))
        except ValueError:
            continue
        _add_num(values, v)
        unit = m.group(2)
        if unit in _SCALE:
            _add_num(values, v * _SCALE[unit])
    return values


def article_number_set(article_text):
    """Numbers the article itself states: digits, spelled-out numbers,
    and fraction phrases — the ground truth claims must match."""
    t = norm_text(article_text)
    values = extract_numbers(article_text)
    # Spelled-out numbers ("nine", "twenty-five handled as two tokens —
    # good enough: both words land in the set).
    for w, v in _WORD_NUMS.items():
        if re.search(rf"\b{w}\b", t):
            _add_num(values, v)
    # "one-half of 1%" -> 0.5 (a percentage value)
    for m in re.finditer(r"one-half of ([\d.]+)\s*%", t):
        _add_num(values, float(m.group(1)) / 2.0)
    if re.search(r"\bone-half\b", t):
        _add_num(values, 0.5)
    # "a quarter" (of production, etc.) -> 25 in % terms, 0.25 raw
    if re.search(r"\ba quarter\b|\bquarter below\b|\bdown a quarter\b", t):
        _add_num(values, 25.0)
        _add_num(values, 0.25)
    # "a fifth more/less" -> 20%
    if re.search(r"\ba fifth\b", t):
        _add_num(values, 20.0)
    return values


# ── Name grounding ──────────────────────────────────────────────────────────
_CAP_TOKEN = re.compile(r"^[A-Z][A-Za-z0-9&.'-]*$|^[A-Z][A-Z0-9&.'-]*$")
_LEADING_STOP = {"the", "a", "an"}


def is_shout_case(text):
    """Mostly-uppercase strings (hook lines are rendered ALL CAPS):
    capitalization there carries no proper-noun signal."""
    letters = [c for c in text if c.isalpha()]
    if len(letters) < 4:
        return False
    return sum(1 for c in letters if c.isupper()) / len(letters) > 0.7


def extract_entities(text):
    """Capitalized multi-word runs in `text` (candidate proper nouns).
    Shout-case strings yield none (see is_shout_case); their factual
    anchors are numbers and digit-bearing tokens, checked separately."""
    if is_shout_case(text):
        return []
    # Runs break at punctuation boundaries too — "Endowed Chair,
    # University of X" is two entities, not one merged mega-entity.
    tokens = []
    for seg_i, seg in enumerate(re.split(r"[,;:()\[\]—–/]", text)):
        for tok in re.findall(r"[A-Za-z0-9][A-Za-z0-9&.'$-]*", seg):
            tokens.append((seg_i, tok))
        tokens.append((seg_i, None))
    runs, cur = [], []
    for _, tok in tokens:
        base = tok.strip(".,;:!?()\"") if tok else None
        if base and _CAP_TOKEN.match(base) and not base.isdigit():
            cur.append(base)
        else:
            if len(cur) >= 2:
                runs.append(cur)
            cur = []
    if len(cur) >= 2:
        runs.append(cur)
    out = []
    for run in runs:
        while run and run[0].lower().rstrip(".") in _LEADING_STOP:
            run = run[1:]
        if len(run) >= 2:
            out.append(" ".join(run))
    return out


def _entity_like_token(tok):
    """A single token that can stand as an entity on its own: carries a
    digit or hyphen (H-1B), or is an acronym (UAH, APS, NASA). Plain
    capitalized words may NOT ground singly — too weak a signal."""
    return bool(re.search(r"\d", tok)) or "-" in tok \
        or (len(tok) >= 3 and tok.isupper())


# Words that commonly open a sentence and get capitalized for that
# reason only — they glom onto a following proper noun ("Same Diwali",
# "Check H-1B status..."). Dropping them is safe when the remainder
# verifies on its own.
_SENTENCE_OPENERS = {
    "same", "this", "that", "these", "those", "check", "now", "here",
    "there", "but", "and", "so", "first", "next", "then", "when",
    "while", "after", "before", "watch", "look", "note", "remember",
}


def entity_grounded(entity, article_norm, article_raw=""):
    """Entity (original case) must appear in normalized article text.
    Sentence-initial capitalization is ambiguous, so if the full run
    fails we also try the run without its first token — accepted only
    when the remainder verifies independently: a multi-word run, an
    entity-like single token (H-1B, UAH), or — when the dropped word
    is a common sentence opener — a token the article itself prints
    capitalized."""
    e = norm_text(entity)
    if e in TEMPLATE_OWNED:
        return True
    if e and e in article_norm:
        return True
    toks = e.split()
    if len(toks) >= 3 and " ".join(toks[1:]) in article_norm:
        return True
    orig_toks = entity.split()
    if len(toks) == 2 and len(orig_toks) == 2:
        if _entity_like_token(orig_toks[1]) and toks[1] in article_norm:
            return True
        if toks[0] in _SENTENCE_OPENERS and article_raw and re.search(
                rf"\b{re.escape(orig_toks[1])}\b", article_raw):
            return True
    return False


# ── Deterministic gate ──────────────────────────────────────────────────────
def deterministic_check(claims, script, article):
    article_raw = " ".join([article.get("headline") or "",
                            article.get("subheadline") or "",
                            article.get("body") or ""])
    article_norm = norm_text(article_raw)
    numbers_in_article = article_number_set(article_raw)
    results = []
    for c in claims:
        text = c["text"]
        nums = extract_numbers(text)
        missing_nums = sorted(v for v in nums
                              if v not in numbers_in_article)
        years = sorted(v for v in nums
                       if 1900 <= v <= 2099 and float(v).is_integer())
        entities = extract_entities(text)
        missing_entities = [e for e in entities
                            if not entity_grounded(e, article_norm,
                                                   article_raw)]
        if is_shout_case(text):
            # Shout-case lines: digit-bearing tokens (H-1B, B-2) are
            # factual anchors and must ground individually.
            for tok in re.findall(r"[A-Za-z][A-Za-z0-9-]*\d[A-Za-z0-9-]*"
                                  r"|\d+[A-Za-z][A-Za-z0-9-]*", text):
                if norm_text(tok) not in article_norm:
                    missing_entities.append(tok)
        ok = not missing_nums and not missing_entities
        detail = {}
        if missing_nums:
            detail["ungrounded_numbers"] = missing_nums
        if years:
            detail["years_checked"] = [int(y) for y in years]
        if missing_entities:
            detail["ungrounded_entities"] = missing_entities
        results.append({**c, "numbers": sorted(nums),
                        "entities": entities,
                        "deterministic": "pass" if ok else "fail",
                        "detail": detail})
    # Eyebrow closed vocabulary.
    eyebrow = (script.get("hook_stat") or {}).get("eyebrow") or ""
    eyebrow = eyebrow.strip().upper()
    eb_ok, eb_detail = True, "closed vocabulary"
    if eyebrow:
        m = _EYEBROW_YEAR_RE.match(eyebrow)
        if eyebrow in CLOSED_EYEBROWS:
            pass
        elif m and float(m.group(1)) in numbers_in_article:
            eb_detail = "ELECTIONS <grounded year>"
        else:
            eb_ok = False
            eb_detail = (f"eyebrow {eyebrow!r} not in closed vocabulary "
                         f"and not a grounded ELECTIONS year")
    # key_entities wholesale.
    ke_results = []
    for ke in script.get("key_entities") or []:
        ke_ok = norm_text(ke) in article_norm or \
            entity_grounded(ke, article_norm, article_raw)
        ke_results.append({"entity": ke,
                           "deterministic": "pass" if ke_ok else "fail"})
    return results, {"eyebrow": eyebrow, "eyebrow_ok": eb_ok,
                     "eyebrow_detail": eb_detail,
                     "key_entities": ke_results}


# ── LLM layer (GPT-4o-mini via curl — AGENTS.md: curl for API POSTs) ───────
_LLM_MODEL = "gpt-4o-mini"
_PRICE_IN, _PRICE_OUT = 0.15 / 1e6, 0.60 / 1e6   # USD per token

# Fields the LLM never judges: the hook eyebrow is a section label,
# governed by the closed-vocabulary / grounded-year rule in the
# deterministic layer. Sending it to the judge only invites a verdict
# slot spent on a non-claim ("no 'BY THE NUMBERS' section exists in
# the article" — true, and irrelevant).
_JUDGE_EXEMPT_FIELDS = {"hook_stat.eyebrow"}


def _judge_call(ask_claims, article):
    """One judge round over `ask_claims` (claim dicts with field/text).
    Returns (raw_verdicts, cost_usd, error): raw_verdicts is the
    judge's own list of {"id", "claim", "verdict", "reason"} dicts —
    UNTRUSTED in order, numbering and completeness. Attribution is
    attribute_verdicts' job, never this function's."""
    key = os.environ.get("OPENAI_API_KEY")
    if not key:
        return None, 0.0, "OPENAI_API_KEY not set"
    body_text = norm_text(" ".join([article.get("headline") or "",
                                    article.get("subheadline") or "",
                                    article.get("body") or ""]))[:7000]
    claim_lines = "\n".join(
        f"{i + 1}. [id: {c['field']}] {c['text']}"
        for i, c in enumerate(ask_claims))
    prompt = (
        "You are a strict fact-checker for short news videos. Below is a "
        "news article and a list of on-screen text claims for a video "
        "about it. For EACH claim decide:\n"
        '- "supported": every fact it asserts (names, numbers, dates, '
        "titles, attributions) is present in or directly entailed by the "
        "article. Paraphrase is fine. Advice or imperatives to the "
        "viewer (e.g. 'check your local rules') count as supported "
        "UNLESS they assert a specific fact the article does not "
        "contain.\n"
        '- "unsupported": it asserts anything absent from, or '
        "contradicted by, the article.\n"
        "Reply with ONLY a JSON object: "
        '{"verdicts": [{"id": "<the claim\'s id, copied exactly>", '
        '"claim": "<the claim text, copied exactly word for word>", '
        '"verdict": "supported"|"unsupported", '
        '"reason": "<=20 words"}]} with exactly one verdict per claim '
        "in the list. Copying the claim text exactly is how your "
        "verdict is matched back to its claim — do not paraphrase, "
        "shorten or renumber it.\n\n"
        f"ARTICLE:\n{body_text}\n\nCLAIMS:\n{claim_lines}")
    payload = {"model": _LLM_MODEL, "temperature": 0,
               "response_format": {"type": "json_object"},
               "messages": [{"role": "user", "content": prompt}]}
    proc = subprocess.run(
        ["curl", "-sS", "-X", "POST",
         "https://api.openai.com/v1/chat/completions",
         "-H", f"Authorization: Bearer {key}",
         "-H", "Content-Type: application/json",
         "-d", json.dumps(payload)],
        capture_output=True, text=True, timeout=120)
    if proc.returncode != 0:
        return None, 0.0, f"curl failed: {proc.stderr[:200]}"
    try:
        resp = json.loads(proc.stdout)
        usage = resp.get("usage") or {}
        cost = (usage.get("prompt_tokens", 0) * _PRICE_IN
                + usage.get("completion_tokens", 0) * _PRICE_OUT)
        content = resp["choices"][0]["message"]["content"]
        verdicts = json.loads(content)["verdicts"]
        if not isinstance(verdicts, list):
            raise ValueError("verdicts is not a list")
        return verdicts, cost, None
    except Exception as e:
        return None, 0.0, f"unparseable LLM response: {e}"


def attribute_verdicts(pending, raw_verdicts):
    """Attribute raw judge verdicts to the claims they are about.

    `pending` is a list of (orig_index, claim) pairs still awaiting a
    verdict. A verdict is attributed by, in order:
      1. its echoed claim text — an exact normalized match against a
         still-unjudged claim (when several unjudged claims share the
         text, the one whose id the verdict also carries wins);
      2. its claim id — the field name copied from the claim list.
    Positional order is NEVER used: the 2026-10-24 SpaceX judge
    answered 12 of 14 claims and numbered its tail verdicts onto the
    wrong fields, which the old positional mapping recorded as
    supported verdicts for claims they were not about, and "missing"
    for the two claims that never got one. Verdicts that match no
    pending claim (stray non-claims, duplicates, unknown verdict
    strings) are dropped and counted, never shifted onto a neighbour.

    Returns (attributed, unmatched_count): attributed maps orig_index
    -> {"verdict", "reason"}."""
    by_text = {}
    for orig_idx, c in pending:
        by_text.setdefault(norm_text(c["text"]), []).append(orig_idx)
    by_field = {c["field"]: orig_idx for orig_idx, c in pending}
    attributed, taken, unmatched = {}, set(), 0
    for v in raw_verdicts or []:
        if not isinstance(v, dict):
            unmatched += 1
            continue
        verdict = str(v.get("verdict", "")).strip().lower()
        if verdict not in ("supported", "unsupported"):
            unmatched += 1
            continue
        echo = norm_text(str(v.get("claim") or ""))
        vid = str(v.get("id") or "").strip()
        target = None
        if echo:
            cands = [i for i in by_text.get(echo, []) if i not in taken]
            if len(cands) == 1:
                target = cands[0]
            elif len(cands) > 1:
                id_idx = by_field.get(vid)
                target = id_idx if id_idx in cands else cands[0]
        if target is None:
            id_idx = by_field.get(vid)
            if id_idx is not None and id_idx not in taken:
                target = id_idx
        if target is None:
            unmatched += 1
            continue
        taken.add(target)
        attributed[target] = {"verdict": verdict,
                              "reason": str(v.get("reason", ""))}
    return attributed, unmatched


def llm_check(claims, article):
    """Judge every judge-eligible claim; attribute by echo/id.

    Returns (verdict_map, cost_usd, error, meta). verdict_map is keyed
    by 1-based position in the FULL claims list (run_gate's lookup).
    Every eligible claim ends with an entry: a real verdict, or
    "judge_error" when the judge produced nothing attributable for it
    even after the single re-ask — run_gate holds those claims, but
    the report labels them as judge failures, not unsupported facts.
    meta carries {"rounds", "reasked", "unmatched_verdicts",
    "judge_error_claims"} for the report."""
    eligible = [(i, c) for i, c in enumerate(claims)
                if c["field"] not in _JUDGE_EXEMPT_FIELDS]
    meta = {"rounds": 0, "reasked": [], "unmatched_verdicts": 0,
            "judge_error_claims": []}
    attributed, total_cost = {}, 0.0
    pending = list(eligible)
    for round_no in (1, 2):
        if not pending:
            break
        raw, cost, err = _judge_call([c for _, c in pending], article)
        if err:
            return None, total_cost, err, meta
        total_cost += cost
        meta["rounds"] = round_no
        got, unmatched = attribute_verdicts(pending, raw)
        meta["unmatched_verdicts"] += unmatched
        attributed.update(got)
        pending = [(i, c) for i, c in pending if i not in attributed]
        if pending and round_no == 1:
            meta["reasked"] = [c["field"] for _, c in pending]
    for i, c in pending:
        attributed[i] = {
            "verdict": "judge_error",
            "reason": "judge returned no attributable verdict for "
                      "this claim after one re-ask"}
        meta["judge_error_claims"].append(c["field"])
    out = {i + 1: v for i, v in attributed.items()}
    return out, total_cost, None, meta


# ── Article loading ─────────────────────────────────────────────────────────
def fetch_article_by_slug(slug):
    url = os.environ.get("SUPABASE_URL")
    key = os.environ.get("SUPABASE_SERVICE_ROLE_KEY")
    if not url or not key:
        raise RuntimeError("SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY "
                           "not set (source .env.supabase)")
    api = (f"{url}/rest/v1/p2_articles?select=id,slug,headline,"
           f"subheadline,category,image_url,body,sources"
           f"&slug=eq.{slug}")
    proc = subprocess.run(
        ["curl", "-sS", api, "-H", f"apikey: {key}",
         "-H", f"Authorization: Bearer {key}"],
        capture_output=True, text=True, timeout=60)
    rows = json.loads(proc.stdout)
    if not rows:
        raise RuntimeError(f"no article with slug {slug!r}")
    return rows[0]


# ── Gate entry point ────────────────────────────────────────────────────────
def run_gate(script, article, use_llm=True):
    claims = collect_claims(script)
    results, extra = deterministic_check(claims, script, article)
    llm_map, llm_cost, llm_err, llm_meta = (None, 0.0, None, {})
    if use_llm:
        llm_map, llm_cost, llm_err, llm_meta = llm_check(claims, article)
    held = []
    for i, r in enumerate(results):
        verdicts = {"deterministic": r["deterministic"]}
        if llm_map is not None:
            lv = llm_map.get(i + 1)
            if lv:
                verdicts["llm"] = lv["verdict"]
                r["llm_reason"] = lv["reason"]
            elif r["field"] in _JUDGE_EXEMPT_FIELDS:
                # Never sent to the judge (section label, not a
                # claim) — an absent verdict here is by design.
                verdicts["llm"] = None
                r["llm_reason"] = ""
            else:
                verdicts["llm"] = "missing"
                r["llm_reason"] = ""
        r["verdicts"] = verdicts
        # The eyebrow kicker is a section label, not a factual claim:
        # it is governed by the closed-vocabulary / grounded-year rule
        # below, so the LLM's article-grounding verdict does not apply
        # to it (it has nothing to ground against).
        llm_applies = r["field"] != "hook_stat.eyebrow"
        failed = r["deterministic"] != "pass" or \
            (llm_applies
             and verdicts.get("llm") not in (None, "supported"))
        r["verdict"] = "fail" if failed else "pass"
        if failed:
            held.append(r["field"])
    if use_llm and llm_map is None:
        # Fail closed: a gate that silently degrades when its LLM layer
        # is down is how the old system ended up asserting QA it never
        # ran. Deterministic-only mode is an explicit --no-llm choice.
        held.append(f"llm_layer_unavailable: {llm_err}")
    if not extra["eyebrow_ok"]:
        held.append("hook_stat.eyebrow")
    for ke in extra["key_entities"]:
        if ke["deterministic"] != "pass":
            held.append(f"key_entities:{ke['entity']}")
    report = {
        "gate": "reel_factcheck.py",
        "article_slug": article.get("slug"),
        "verdict": "fail" if held else "pass",
        "held_claims": held,
        "claims": results,
        "eyebrow": {"value": extra["eyebrow"], "ok": extra["eyebrow_ok"],
                    "detail": extra["eyebrow_detail"]},
        "key_entities": extra["key_entities"],
        "judge_errors": llm_meta.get("judge_error_claims", []),
        "llm": {"model": _LLM_MODEL if use_llm else None,
                "ran": llm_map is not None,
                "error": llm_err,
                "cost_usd": round(llm_cost, 6),
                "rounds": llm_meta.get("rounds", 0),
                "reasked_claims": llm_meta.get("reasked", []),
                "unmatched_verdicts": llm_meta.get(
                    "unmatched_verdicts", 0),
                "judge_error_claims": llm_meta.get(
                    "judge_error_claims", [])},
    }
    return report


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--script", required=True)
    ap.add_argument("--article", default=None,
                    help="local article JSON file")
    ap.add_argument("--slug", default=None,
                    help="fetch the article from Supabase by slug")
    ap.add_argument("--out", default=None, help="write report JSON here")
    ap.add_argument("--no-llm", action="store_true")
    args = ap.parse_args()

    if not Path(args.script).exists():
        print(f"🚫 script not found: {args.script}", file=sys.stderr)
        return 4
    script = json.loads(Path(args.script).read_text())
    try:
        if args.article:
            article = json.loads(Path(args.article).read_text())
            if isinstance(article, list):   # raw Supabase REST dump
                article = article[0]
        elif args.slug:
            article = fetch_article_by_slug(args.slug)
        else:
            print("🚫 need --article or --slug", file=sys.stderr)
            return 4
    except Exception as e:
        print(f"🚫 article load failed: {e}", file=sys.stderr)
        return 4

    report = run_gate(script, article, use_llm=not args.no_llm)
    if args.out:
        Path(args.out).write_text(json.dumps(report, indent=2))
    n_pass = sum(1 for c in report["claims"] if c["verdict"] == "pass")
    print(f"fact-check: {n_pass}/{len(report['claims'])} claims pass · "
          f"eyebrow ok={report['eyebrow']['ok']} · "
          f"LLM {'ran' if report['llm']['ran'] else 'NOT RUN'}"
          f" (cost ${report['llm']['cost_usd']})")
    if report["verdict"] == "fail":
        print(f"🚫 HELD — failing: {', '.join(report['held_claims'])}",
              file=sys.stderr)
        for c in report["claims"]:
            if c["verdict"] == "fail":
                print(f"   ✗ [{c['field']}] {c['text']!r} "
                      f"{json.dumps(c.get('detail') or {})} "
                      f"{c.get('llm_reason', '')}", file=sys.stderr)
        return 1
    print("✅ fact-check PASS — every claim grounded in the article")
    return 0


if __name__ == "__main__":
    sys.exit(main())
